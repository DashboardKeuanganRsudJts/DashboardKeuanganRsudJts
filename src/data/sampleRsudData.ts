export function calculateUmurHari(tanggalPelayanan: string): { hari: number; kategori: UmurPiutangCategory } {
  const serviceDate = new Date(tanggalPelayanan);
  const today = new Date('2026-08-25'); // Using current environment context date or today
  const diffTime = Math.abs(today.getTime() - serviceDate.getTime());
  const hari = Math.ceil(diffTime / (1000 * 60 * 60 * 24));

  let kategori: UmurPiutangCategory = '0-30 Hari (Lancar)';
  if (hari <= 30) {
    kategori = '0-30 Hari (Lancar)';
  } else if (hari <= 60) {
    kategori = '31-60 Hari (Kurang Lancar)';
  } else if (hari <= 90) {
    kategori = '61-90 Hari (Diragukan)';
  } else {
    kategori = '>90 Hari (Macet / Kritis)';
  }

  return { hari, kategori };
}

